def ob(i, tool, out, status='ok', args=None, backend=None, source='case'):
    return EV2.make_observation(i, tool, args or {}, status, out if isinstance(out, str) else json.dumps(out), backend, source)


ABSENT = object()


def probe(tags=ABSENT, chapters=None, drop=(), stderr=''):
    fmt = {'format_name': 'mov,mp4,m4a', 'duration': '20.0'}
    if tags is not ABSENT:
        fmt['tags'] = tags
    d = {'exit_code': 0, 'stderr': stderr, 'format': fmt, 'streams': [{'index': 0, 'codec_type': 'audio', 'codec_name': 'aac', 'channels': 2}]}
    if chapters is not None:
        d['chapters'] = chapters
    for k in drop:
        d['format'].pop(k, None)
    return d



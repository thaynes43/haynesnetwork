class PresenceStates(unittest.TestCase):
    def test_the_six_states_never_collapse(self):
        self.assertEqual([PR.state_of(v) for v in (None, '', [], {}, '  ', False, 0, 0.0, 'x', [0], {'a': None}, True, 1)],
                         ['null', 'empty', 'empty', 'empty', 'empty', 'false', 'zero', 'zero', 'populated', 'populated', 'populated', 'populated', 'populated'])
        self.assertEqual(PR.lookup({'a': {}}, ('a', 'b')), [(('a', 'b'), 'absent', None)])
        self.assertEqual(PR.lookup({'a': {'b': None}}, ('a', 'b')), [(('a', 'b'), 'null', None)])

    def rows(self, o):
        return {r['path']: r['presence'] for r in PR.observation_presence(o)}

    def test_every_typed_source_distinguishes_absent_empty_and_populated(self):
        cases = [
            ('ffprobe', lambda v: probe(tags=v), 'format.tags'),
            ('audiobook_inspect', lambda v: {'format': 'mp4', 'duration_s': 20, 'audio_streams': [{'codec': 'aac'}], **({} if v == 'ABSENT' else {'tags': v})}, 'tags'),
            ('epub_inspect', lambda v: {'status': 'ok', 'spine_items': 3, **({} if v == 'ABSENT' else {'dc_title': v})}, 'dc_title'),
            ('decode_sample', lambda v: {'exit_code': 0, 'out_time': '00:00:04', **({} if v == 'ABSENT' else {'frames': v})}, 'frames'),
            ('audio_sample', lambda v: {**({} if v == 'ABSENT' else {'rms_dbfs': v})}, 'rms_dbfs'),
            ('ocr', lambda v: {'t_s': 1.0, **({} if v == 'ABSENT' else {'text': v})}, 'text'),
            ('arr_lookup', lambda v: {'app': 'sonarr', **({} if v == 'ABSENT' else {'file': v})}, 'file'),
            ('prior_record', lambda v: {'evidence_method': 'x', **({} if v == 'ABSENT' else {'observed': v})}, 'observed'),
        ]
        for tool, build, path in cases:
            for value, want in (('ABSENT', 'absent'), (None, 'null'), ({}, 'empty'), ([], 'empty'), ('', 'empty'), (False, 'false'), (0, 'zero'), ('x', 'populated')):
                if tool == 'ffprobe':
                    got = self.rows(ob('e1', tool, probe(tags=ABSENT if value == 'ABSENT' else value)))
                else:
                    got = self.rows(ob('e1', tool, build(value)))
                self.assertEqual(got.get(path), want, (tool, value))

    def test_live_collector_records_are_typed_too(self):
        live = {'tool': 'probe', 'status': 'ok', 'coverage': {'verified': ['x'], 'not_verified': []}, 'output': {'format': 'mp4', 'tags': {}, 'streams': [], 'chapters': None}}
        got = self.rows(ob('t1', 'ffprobe', live, backend='live', source='tool'))
        self.assertEqual((got['output.tags'], got['output.streams'], got['output.chapters'], got['output.duration_s']), ('empty', 'empty', 'null', 'absent'))
        book = {'tool': 'audiobook', 'status': 'ok', 'coverage': {'verified': [], 'not_verified': []}, 'output': {'files': [{'tags': {}}, {'tags': {'title': 'a'}}]}}
        got = self.rows(ob('t1', 'audiobook_inspect', book, backend='live', source='tool'))
        self.assertEqual((got['output.files.0.tags'], got['output.files.1.tags']), ('empty', 'populated'))

    def test_a_source_that_did_not_run_is_not_checked_and_an_unreadable_one_unknown(self):
        self.assertEqual(set(self.rows(ob('t1', 'ffprobe', 'tool ffprobe is not offered', status='unavailable')).values()), {'not_checked'})
        self.assertEqual(set(self.rows(ob('t1', 'ffprobe', 'ffprobe exceeded the 60 s tool timeout', status='timeout')).values()), {'not_checked'})
        self.assertEqual(set(self.rows(ob('t1', 'ffprobe', 'garbled {not json')).values()), {'unknown'})


class ExplicitEmptiesComeBack(unittest.TestCase):
    """Hypothesis 4: v2 collapses `tags: {}` and an empty chapter list into absence; v3 keeps them, and only them."""

    def v2v3(self, observations, media='audiobook'):
        v2, _ = FX.canonical_facts(observations, {}, media, 'v2')
        v3, _ = FX.canonical_facts(observations, {}, media, 'v3')
        return v2, v3

    def added(self, v2, v3):
        rest = list(v3)
        for f in v2:
            rest.remove(f)            # v2 is a sub-multiset of v3 (raises otherwise)
        return rest

    def test_empty_tags_and_chapters_are_restored_with_their_presence(self):
        v2, v3 = self.v2v3([ob('e1', 'ffprobe', probe(tags={}, chapters=[]))])
        added = self.added(v2, v3)
        self.assertEqual(sorted((f[8], f[9], f[10]) for f in added), [('chapters', 'empty', '[]'), ('stderr_lines', 'empty', '[]'), ('tags', 'empty', '{}')])
        self.assertTrue(all(f[0] == 'e1' and f[3] == 'recorded' and f[4] == 'ran' for f in added))

    def test_paired_negatives_absent_and_populated_add_nothing(self):
        for o in (ob('e1', 'ffprobe', probe(stderr='x')), ob('e1', 'ffprobe', probe(tags={'title': 'T'}, chapters=[{'start': 0, 'end': 1, 'title': 'c'}], stderr='x'))):
            v2, v3 = self.v2v3([o])
            self.assertEqual(self.added(v2, v3), [], o['output'][:60])

    def test_audiobook_and_epub_filters_are_covered(self):
        ab = ob('e1', 'audiobook_inspect', {'format': 'mp4', 'duration_s': 20, 'audio_streams': [{'codec': 'aac'}], 'tags': {}, 'chapters': []})
        ep = ob('e2', 'epub_inspect', {'status': 'ok', 'spine_items': 2, 'dc_title': '', 'dc_creator': 'C', 'spine_heads': []})
        v2, v3 = self.v2v3([ab, ep])
        got = sorted((f[0], f[8], f[9]) for f in self.added(v2, v3))
        self.assertEqual(got, [('e1', 'chapters', 'empty'), ('e1', 'tags', 'empty'), ('e2', 'spine_heads', 'empty'), ('e2', 'title', 'empty')])

    def test_false_and_zero_survive_in_both_and_null_is_not_empty(self):
        o = ob('e1', 'decode_sample', {'exit_code': 0, 'frames': 0, 'out_time': None, 'stderr': ''}, args={'at': 8})
        v2, v3 = self.v2v3([o], 'tv')
        self.assertIn(('frames', 'zero', '0'), [(f[8], f[9], f[10]) for f in v2])          # v2 already kept the zero
        self.assertEqual(sorted((f[8], f[9]) for f in self.added(v2, v3)), [('decoded_s', 'null'), ('error_lines', 'empty')])     # a null out_time is kept (third review, P3)


class Deduplication(unittest.TestCase):
    """A16 item 3: one open item per identical statement and scope, every source id kept; reassembly gives each source its own fact."""

    def obs(self):
        return [ob('e1', 'ffprobe', probe(tags={})), ob('e2', 'ffprobe', probe(tags={})), ob('e3', 'arr_lookup', {'app': 'lazylibrarian', 'work': 'W'}),
                ob('e4', 'arr_lookup', {'app': 'lazylibrarian', 'work': 'W'})]

    def test_identical_wording_is_one_item_with_every_source(self):
        r = FX.render(self.obs(), {}, 'audiobook', ['ffprobe', 'arr_lookup'], [])
        texts = [(it['text'], it['sources']) for it in r['open']]
        self.assertIn(('nothing was decoded: stream contents are unchecked by this result', ['e1', 'e2']), texts)
        self.assertIn(('this result is a record or reading, not an integrity check', ['e3', 'e4']), texts)
        self.assertEqual(sum(1 for t, _s in texts if t.startswith('nothing was decoded')), 1)
        for it in r['reference']['items']:
            self.assertNotIn('unresolved', it)                 # shown once, in `open`, never repeated per item
        self.assertEqual(FX.facts_from_body(r['reference']), r['facts'])

    def test_same_words_from_different_observations_stay_two_facts(self):
        facts, _ = FX.canonical_facts(self.obs(), {}, 'audiobook')
        u = [f for f in facts if f[7] == 'unresolved' and f[10] == json.dumps('nothing was decoded: stream contents are unchecked by this result')]
        self.assertEqual(sorted(f[0] for f in u), ['e1', 'e2'])

    def test_conflicts_findings_and_diagnostics_stay_with_their_item(self):
        bad = {'exit_code': 0, 'frames': 27, 'out_time': '00:00:04.000000', 'stderr': '[h264 @ 0x0] error while decoding MB 13 11, bytestream -5', 'ss': 4, 't': 4}
        obs = [ob('e1', 'ffprobe', probe(tags={})), ob('e2', 'decode_sample', bad, args={'ss': 4, 't': 4}), ob('e3', 'decode_sample', bad, args={'ss': 4, 't': 4})]
        r = FX.render(obs, {}, 'tv', ['ffprobe', 'decode_sample'], [])
        items = {it['id']: it for it in r['reference']['items']}
        # status ok with a defect, and exit 0 with decoder errors: two conflicts per item, each kept with its own item
        self.assertEqual([(c['id'], c['kind']) for c in items['e2']['conflicts']], [('e2.c1', 'exit_zero_with_decoder_errors'), ('e2.c2', 'status_ok_with_defect')])
        self.assertEqual([c['id'] for c in items['e3']['conflicts']], ['e3.c1', 'e3.c2'])
        self.assertEqual(len(r['reference']['facts']['e2']['diagnostics']), 1)
        self.assertEqual(len(r['reference']['facts']['e3']['diagnostics']), 1)
        self.assertEqual(sorted(a['id'] for a in r['reference']['alerts'] if a['type'] == 'defect'), ['e2.f1', 'e3.f1'])


class PaginationReconstruction(unittest.TestCase):
    """Shrinking a page must not hide uncertainty behind an unfetched page: every page repeats the alerts and the open-item count, and the pages
    together reassemble to exactly the canonical facts of one unpaginated rendering."""

    def many(self, n=14):
        obs = [ob('e1', 'ffprobe', probe(tags={}, chapters=[{'start': i, 'end': i + 1, 'title': 'Chapter %02d %s' % (i, 'x' * 30)} for i in range(20)]))]
        for i in range(2, n):
            stderr = '[h264 @ 0x0] error while decoding MB 1 %d, bytestream -5' % i if i % 4 == 0 else ''
            obs.append(ob('e%d' % i, 'decode_sample', {'exit_code': 0, 'frames': 40, 'out_time': '00:00:01.000000', 'stderr': stderr, 'ss': i, 't': 1}, args={'ss': i, 't': 1}))
        obs.append(ob('e%d' % n, 'arr_lookup', {'app': 'sonarr', 'note': 'n' * 900, 'file': None}))
        return obs

    def test_pages_reassemble_to_the_canonical_facts_at_every_budget(self):
        obs = self.many()
        caps = [{'tool': 'decode_sample', 'backend': 'replay', 'available': True, 'offsets_s': [0, 4, 8, 12, 16], 'window_s': 4, 'full_decode': 'recorded'}]
        for budget in (8192, 4096, 2560):
            r = FX.render(obs, {}, 'tv', ['ffprobe', 'decode_sample', 'arr_lookup'], caps, budget=budget)
            self.assertTrue(all(b <= budget for b in r['page_bytes']), (budget, r['page_bytes']))
            body = FX.reassemble(r['pages'])
            self.assertEqual(FX.facts_from_body(body), r['facts'], budget)
            self.assertEqual([it['id'] for it in body['open']], [it['id'] for it in r['open']], budget)
            for p in r['pages']:                                    # page-local alerts and the count of open items, on every page
                self.assertEqual(p['alerts'], r['pages'][0]['alerts'])
                self.assertEqual(p['open_total'], len(r['open']))
            if budget == 2560:
                self.assertGreater(len(r['pages']), 1)

    def test_neutral_wording_and_no_verdict_fields(self):
        r = FX.render(self.many(), {}, 'tv', ['ffprobe', 'decode_sample', 'arr_lookup'], [])
        blob = json.dumps(r['pages']).lower()
        for word in ('required', 'must ', 'needed', 'need to', 'should ', 'sufficient', 'solvable', 'recommended', 'healthy'):
            self.assertNotIn(word, json.dumps([it['text'] for it in r['open']]).lower(), word)
        for field in RB.FORBIDDEN_FIELDS:
            self.assertNotIn('"%s"' % field, blob, field)


class Leakage(unittest.TestCase):
    """No truth, label or uncalled result reaches v3 output: the renderer has no case parameter, and an observation it is not given cannot appear."""

    def test_render_takes_no_case_and_reads_no_hidden_field(self):
        import inspect
        self.assertEqual(list(inspect.signature(FX.render).parameters), ['observations', 'context', 'media_type', 'tools_offered', 'capabilities', 'alias', 'budget', 'frame'])
        src = '\n'.join(inspect.getsource(m) for m in (FX, PR))
        for field in ("'truth'", "'supported_actions'", "'accepted_classes'", "'solvable'", "'family'", "'provenance'", "'outcome_step'", "'inject_tool_failure'", "'case_id'"):
            self.assertNotIn(field, src, field)

    def test_an_uncalled_result_never_appears(self):
        shown = [ob('e1', 'ffprobe', probe(tags={}))]
        secret = ob('t9', 'decode_sample', {'exit_code': 0, 'frames': 1, 'out_time': '00:00:01', 'stderr': 'ZQX-SECRET moov atom not found'})
        caps = [{'tool': 'decode_sample', 'backend': 'replay', 'available': True, 'offsets_s': [0, 4], 'window_s': 4, 'full_decode': 'recorded'}]
        a = FX.render(shown, {}, 'tv', ['ffprobe', 'decode_sample'], caps)
        self.assertNotIn('ZQX-SECRET', json.dumps(a))
        self.assertNotIn('t9', json.dumps(a['pages']))
        del secret



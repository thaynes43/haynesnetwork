"""Contract v3, hypothesis 1 and A16 item 4: typed open items and their capability links (`available_check`).

An open item is an unresolved statement of the v2 typed layer (its exact text, kept) with a typed SCOPE, or a not-checked part of the
coverage matrix.  A link is a PURE FUNCTION of (the open item's scope, the observations already shown, the capabilities already advertised,
the static tool semantics in rubric.TOOL_SEMANTICS).  It says "this offered tool may inspect this scope", never "it will resolve it", and it
carries no result: the function never receives one.  Offsets come from the advertisement (every advertised offset whose window intersects
the scope, in advertised order), never from a recorded result.  Zero, one or many candidates; availability available / unavailable /
unknown / called / called_failed.  The remaining budget is not an input.
"""
import re

from ... import evidence_v2 as EV2
from . import rubric as RB

# the v2 unresolved texts are generated by fixed harness code (evidence_v2._derive_* and _finish); each template maps to a scope type
_TEMPLATES = (
    (r'^nothing was decoded: stream contents are unchecked by this result$', 'decode_interval'),
    (r'^nothing was decoded: chapter and part structure is as declared by the container$', 'decode_interval'),
    (r'^which streams were decoded is not recorded$', 'stream_selection_of_window'),
    (r'^this result is a record or reading, not an integrity check$', 'statement_kind'),
    (r'^no body text beyond the shown spine heads was read$', 'epub_body_beyond_heads'),
    (r'^only the first \d+ of \d+ spine items are shown as text', 'epub_body_beyond_heads'),
    (r'^signal statistics only; no speech recognition was run$', 'speech'),
    (r'^a full decode was requested; the result does not say whether it covers the whole file$', 'whole_file_decode'),
    (r'^the whole file was not decoded', 'whole_file_decode'),
    (r'^the full decode did not run to the end of the file$', 'whole_file_decode'),
    (r'^whether the full decode ran to the end of the file is not shown$', 'whole_file_decode'),
    (r'^the tool says the decode reached the end', 'whole_file_decode'),
    (r'^the container duration is not stated$', 'container_duration'),
    (r'^the result lists no streams$', 'stream_list'),
    (r'^\d+ chapters are not listed in this result$', 'declared_chapters'),
    (r'^this call settled nothing about ', 'repeat_of_call'),
    (r'^the call timed out', 'repeat_of_call'),
    (r'^the answer is incomplete \(status partial\)', 'repeat_of_call'),
    (r'^the recorded fields do not say whether this check was clean$', 'repeat_of_call'),
    (r'^the decoder printed ', 'repeat_of_call'),
    (r'^the window decoded no frames', 'repeat_of_call'),
    (r'^the sampler stopped at its input quota', 'repeat_of_call'),
    (r'^the covered span is not recorded', 'repeat_of_call'),
    (r'^the recorded result states no exit code$', 'repeat_of_call'),
    (r'^the result states no frames', 'repeat_of_call'),
    (r'^the decode was stopped at its time limit', 'repeat_of_call'),
    (r'^the tool output was cut before it reached the model', 'presentation_cut'),
    (r'^the output has a shape this layer does not read', 'other'),
)
_TEMPLATE_RX = [(re.compile(p), s) for p, s in _TEMPLATES]
NO_TOOL_SCOPES = ('stream_selection_of_window', 'epub_body_beyond_heads', 'speech', 'statement_kind', 'presentation_cut', 'other')
FULL_AVAILABLE = ('recorded', 'on request')        # prefixes of an advertised full_decode that mean a whole-file request is served
FULL_UNAVAILABLE = ('not_recorded', 'not_possible', 'requested as a 4 s window')


def scope_type(text):
    t = ' '.join(str(text).split())
    for rx, s in _TEMPLATE_RX:
        if rx.search(t):
            return s
    return 'other'


def _call_matches(obs, tool, args):
    """An equivalent call is already shown (case evidence counts: it ran)."""
    if obs['tool'] != tool:
        return False
    a = obs.get('args') or {}
    if 'full' in args:
        return a.get('full') is True or a.get('t') == 'full'
    if 'at' in args:
        if a.get('full') is True or a.get('t') == 'full':
            return False
        at = next((a[k] for k in ('at', 'ss') if isinstance(a.get(k), (int, float)) and not isinstance(a.get(k), bool)), None)
        return float(at if at is not None else 0.0) == float(args['at'])     # a window with no stated start starts at 0 (the tools' default)
    return True


def _availability(tool, args, caps, shown):
    hit = [o for o in shown if _call_matches(o, tool, args)]
    if hit:
        return ('called_failed' if all(o['status'] in ('error', 'timeout', 'unavailable') for o in hit) else 'called'), [o['id'] for o in hit]
    cap = caps.get(tool)
    if cap is None:
        return 'unknown', []
    if cap.get('available') is False:
        return 'unavailable', []
    if 'full' in args:
        fd = str(cap.get('full_decode') or '')
        if any(fd.startswith(p) for p in FULL_AVAILABLE) or fd.startswith('bounded run'):
            return 'available', []
        if any(fd.startswith(p) for p in FULL_UNAVAILABLE):
            return 'unavailable', []
        return 'unknown', []
    if cap.get('available') is True:
        return 'available', []
    return 'unknown', []


def _cand(tool, args, scope, caps, shown, offered):
    if tool not in offered:
        return None
    avail, by = _availability(tool, args, caps, shown)
    c = {'tool': tool, 'args': dict(args), 'scope': scope, 'availability': avail}
    if by:
        c['already_shown_as'] = by
    return c


def _interval_offsets(cap, intervals):
    offs = cap.get('offsets_s')
    w = cap.get('window_s') or 4
    if isinstance(offs, list):
        out = []
        for o in offs:
            for a, b in intervals:
                hi = b if b is not None else float('inf')
                if o < hi and o + w > a:
                    out.append(o)
                    break
        return out
    return [intervals[0][0]] if intervals else []


def links_for(item, capabilities, shown, tools_offered, media_type=None):
    """-> list of candidates for one open item.  `capabilities` is the advertised list, `shown` the observations shown so far (dicts with id, tool,
    args, status), `tools_offered` the case's tools_available.  No result, budget, truth or label is an input."""
    caps = {c.get('tool'): c for c in capabilities or [] if isinstance(c, dict)}
    offered = list(tools_offered or [])
    st = item['scope']['type']
    out = []
    if st in NO_TOOL_SCOPES:
        return out
    if st == 'decode_interval':
        ivs = item['scope'].get('intervals') or [[0.0, None]]
        cap = caps.get('decode_sample') or {}
        for o in _interval_offsets(cap, ivs):
            out.append(_cand('decode_sample', {'at': o}, st, caps, shown, offered))
        out.append(_cand('decode_sample', {'full': True}, st, caps, shown, offered))
    elif st == 'whole_file_decode':
        out.append(_cand('decode_sample', {'full': True}, st, caps, shown, offered))
    elif st in ('container', 'container_duration', 'stream_list', 'declared_tags', 'declared_chapters', 'client_fields'):
        for tool in ('ffprobe', 'audiobook_inspect'):
            if st in RB.TOOL_SEMANTICS[tool]['scopes']:
                out.append(_cand(tool, {}, st, caps, shown, offered))
    elif st == 'package':
        out.append(_cand('epub_inspect', {}, st, caps, shown, offered))
    elif st == 'repeat_of_call':
        src = next((o for o in shown if o['id'] in item.get('sources', [])), None)
        if src is not None and src['tool'] in RB.TOOL_SEMANTICS:
            a = {k: v for k, v in (src.get('args') or {}).items() if k in ('at', 'full')}
            if src['tool'] in ('decode_sample',) and not a:
                a = {'at': (src.get('args') or {}).get('ss', 0)}
            out.append(_cand(src['tool'], a, st, caps, shown, offered))
    elif st == 'catalog_record':
        out.append(_cand('arr_lookup', {}, st, caps, shown, offered))
    return [c for c in out if c is not None]


def _not_checked(cov):
    """The time the coverage matrix (visible) still lists as not checked: the union over its stream rows; the whole known duration when nothing was decoded;
    [0, unknown] when the duration is unknown."""
    dur = cov.get('duration_s')
    whole = [[0.0, dur if isinstance(dur, (int, float)) else None]]
    time = cov.get('time') or {}
    if not isinstance(time, dict) or time.get('state') == 'not_checked' or not time:
        return whole
    spans = []
    for row in time.values():
        nc = row.get('not_checked') if isinstance(row, dict) else None
        if not isinstance(nc, list):
            return whole
        spans += [tuple(x) for x in nc]
    return [list(x) for x in EV2.norm_intervals(spans)]


def open_items(analysis, media_type=None):
    """-> list of open items: {'id', 'text', 'scope': {'type', ...}, 'sources': [ids], 'origin'} -- the v2 unresolved statements grouped by
    identical text AND scope (every source id kept), then the not-checked parts of the coverage matrix.  Neutral wording only."""
    groups, order = {}, []
    for oid in analysis['order']:
        d = analysis['items'][oid]
        for text in d.unresolved:
            stype = scope_type(text)
            scope = {'type': stype}
            if stype == 'decode_interval':
                scope['intervals'] = _not_checked(analysis['coverage'])
            key = (text, EV2.canon(scope))
            if key not in groups:
                groups[key] = {'text': text, 'scope': scope, 'sources': [], 'origin': 'unresolved'}
                order.append(key)
            groups[key]['sources'].append(oid)
    out = [groups[k] for k in order]
    cov = analysis.get('coverage') or {}
    time = cov.get('time') or {}
    if isinstance(time, dict) and time.get('state') != 'not_checked':
        for stream, row in time.items():
            nc = row.get('not_checked') if isinstance(row, dict) else None
            if isinstance(nc, list) and nc:
                out.append({'text': 'not checked: %s, %s' % (stream, ', '.join('%g-%g s' % (a, b) for a, b in nc)), 'scope': {'type': 'decode_interval', 'stream': stream, 'intervals': nc},
                            'sources': list(row.get('by') or []), 'origin': 'coverage.time'})
    pkg = (cov.get('package') or {}).get('stages') if isinstance(cov.get('package'), dict) else None
    if isinstance(pkg, dict):
        rest = [s for s, v in pkg.items() if v in ('not_checked', EV2.UNKNOWN)]
        if rest:
            out.append({'text': 'package stages not checked or unknown: %s' % ', '.join(rest), 'scope': {'type': 'package', 'stages': rest},
                        'sources': list(cov['package'].get('by') or []), 'origin': 'coverage.package'})
    c = cov.get('container')
    if isinstance(c, dict) and c.get('state') == 'not_checked':
        out.append({'text': 'container not checked', 'scope': {'type': 'container'}, 'sources': [], 'origin': 'coverage.container'})
    for i, it in enumerate(out, 1):
        it['id'] = 'u%d' % i
    return out


def attach_links(items, capabilities, shown, tools_offered, media_type=None):
    for it in items:
        it['available_check'] = links_for(it, capabilities, shown, tools_offered, media_type)
    return items
